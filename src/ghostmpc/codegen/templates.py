GENERIC_TRUNCATION_HELPER = '''from Compiler import floatingpoint

def is_negative(value, k):
    """Sign of an accumulator over its own declared width.

    One named entry point rather than an inline ``less_than`` so a profile can
    replace the realization without touching a layer emitter, exactly as the
    truncation helpers do.
    """
    return value.less_than(0, k)

def truncate_generic(value, k, m):
    """Truncate one accumulator through the realization the profile selected.

    ``sfix.round_nearest`` is the deployment default and keeps MP-SPDZ's exact
    nearest ``TruncRing``.  Clearing it selects ``floatingpoint.TruncPrRing``,
    the mask-and-open *probabilistic* truncation, which is named here rather
    than reached implicitly through ``round(k, m, nearest=False)``: it leaks the
    low-order bits of the truncand (MP-SPDZ's own ``trunc_pr_warning``, eprint
    2024/1127) and it is not a saving.  Measured at ring32, k = 24, m = 9 over
    65,536 elements: 102.00 B/element and 16 rounds against 82.12 B and 14
    rounds for the exact bounded truncation, i.e. +24.2% bytes and +2 rounds
    per site (PLAN 8 section 3.1).  It exists only as an ablation.
    """
    if sfix.round_nearest:
        return value.round(k, m, nearest=True)
    return floatingpoint.TruncPrRing(value, k, m, signed=True)
'''

BOUNDED_TRUNCATION_HELPERS = '''from Compiler import comparison, instructions_base, util
from Compiler.GC.types import sbitint
from Compiler.instructions import movs, shrsi

def _trunc_floor_split(value, k, m, split_k, signed=True, return_sign=False):
    # Exact split3 truncation over a public proven width.  No value is opened;
    # only the number of locally split bits changes from RING_BITS to split_k.
    if program.use_split() != 3:
        raise ValueError('bounded truncation requires use_split(3)')
    if not 0 < m < k <= split_k <= RING_BITS:
        raise ValueError('invalid bounded truncation width')
    if signed:
        value = value + (1 << (k - 1))
    columns = value.split_to_n_summands(split_k, 3)
    x = sbitint.wallace_tree_without_finish(columns, True)
    if m == 1:
        low = x[0][1]
        high = (sint.conv(comparison.CarryOutLE(x[1][:-1], x[0][:-1]))
                + sint.conv(x[0][-1]))
    else:
        mid_carry = comparison.CarryOutRawLE(x[1][:m], x[0][:m])
        low = sint.conv(mid_carry) + sint.conv(x[0][m])
        pairs = util.tree_reduce(
            comparison.carry,
            (sbitint.half_adder(xx, yy)
             for xx, yy in zip(x[1][m:-1], x[0][m:-1])))
        top_carry = sint.conv(
            comparison.carry([None, mid_carry], pairs, False)[1])
        high = top_carry + sint.conv(x[0][-1])
    # This helper is called directly on SIMD registers rather than through
    # ``sint.round``'s @vectorize wrapper, so the destination must explicitly
    # retain the source vector width. A scalar destination would make SHRSI
    # overwrite adjacent compiler registers.
    shifted = sint(size=value.size)
    # Left-shifting each additive component discards its bits above k; the
    # following local right shift therefore reconstructs sum floor(u_i/2^m).
    shrsi(shifted, value << (RING_BITS - split_k), RING_BITS - split_k + m)
    result = shifted + sint.conv(low) - (high << (split_k - m))
    if signed:
        result = result - (1 << (k - m - 1))
    if return_sign:
        sign_index = k - 1
        carry_into_sign = comparison.CarryOutRawLE(
            x[1][:sign_index], x[0][:sign_index])
        encoded_sign = (carry_into_sign ^ x[0][sign_index]
                        ^ x[1][sign_index])
        return result, 1 - encoded_sign if signed else 0
    return result

def trunc_floor_bounded(value, k, m, signed=True):
    result = sint(size=value.size)
    _trunc_floor_bounded_cisc(result, value, k, m, signed)
    return result

@instructions_base.cisc
def _trunc_floor_bounded_cisc(result, value, k, m, signed):
    movs(result, _trunc_floor_split(value, k, m, k, signed=signed))

def trunc_round_nearest_bounded(value, k, m, signed=True):
    if m == 0:
        return value
    # This is MP-SPDZ's current half-up definition: add half, enlarge the
    # declaration by one bit, then perform exact signed floor truncation.
    return trunc_floor_bounded(
        value + (1 << (m - 1)), k + 1, m, signed=signed)

def trunc_round_nearest_with_sign(value, k, m, bounded=False):
    if m == 0:
        sign = value.less_than(0, k, maybe_mixed=True)
        return value, sign
    split_k = k + 1 if bounded else RING_BITS
    return _trunc_floor_split(
        value + (1 << (m - 1)), k + 1, m, split_k,
        signed=True, return_sign=True)
'''

TWO_SUMMAND_TRUNCATION_HELPERS = '''from Compiler.instructions import shrsi2

# The three-summand definitions above stay reachable: this block replaces the
# entry points, not the identity they implement.
_generic_truncation = truncate_generic

def _trunc_floor_split2(value, k, m, split_k, signed=True, return_sign=False):
    """Exact truncation over the *two-summand* regrouping of the sharing.

    ``_trunc_floor_split`` splits the accumulator into the three additive
    summands a replicated sharing carries, which is why its two carries land in
    ``{0,1,2}`` and cost two bit injections each, and why a Wallace 3:2
    compressor has to run before any carry network.  Party ``i`` holds
    ``(x_i, x_{i-1})``, so ``A = x_0 + x_2`` is known to P0 alone and
    ``B = x_1`` is held by both P1 and P2 -- the decomposition
    ``split_to_n_summands(k, 2)`` produces.  Over two summands

        x >> m = floor(A/2**m) + floor(B/2**m) + c_low
                 - 2**(split_k - m) * c_high

    with ``c_low`` and ``c_high`` single bits: two injections, no Wallace tree.

    ``shrsi2`` (PLAN 9 Phase 62) supplies the arithmetic half, which ``shrsi``
    cannot: it shifts the two-summand regrouping and re-shares the result as
    ``(t_A - rho, t_B, rho)`` with ``rho`` from the PRNG P0 shares with P2, so
    one ring element travels from P0 to P1 in one round.  Nothing is opened,
    and P1's view of that element is uniform because it does not hold that
    PRNG, so the security argument is perfect and identical in kind to the
    three-summand path.

    Measured at ring32 over 65,536 elements: ``26.625 + 1.250 * k`` bytes per
    element against ``46.125 + 1.500 * k`` and 12 rounds against 14, i.e. -31%
    at the deployed ``k = 24`` (PLAN 9 section 4.3).
    """
    if program.use_split() != 3:
        raise ValueError('two-summand rounding is emitted from the split3 profile')
    if not 0 < m < k <= split_k <= RING_BITS:
        raise ValueError('invalid bounded truncation width')
    if signed:
        value = value + (1 << (k - 1))
    columns = value.split_to_n_summands(split_k, 2)
    x = [[column[0] for column in columns], [column[1] for column in columns]]
    low = comparison.CarryOutRawLE(x[1][:m], x[0][:m])
    pairs = util.tree_reduce(
        comparison.carry,
        (sbitint.half_adder(xx, yy)
         for xx, yy in zip(x[1][m:], x[0][m:])))
    high = sint.conv(comparison.carry([None, low], pairs, False)[1])
    # As in the three-summand helper, the destination has to retain the source
    # vector width explicitly: this is called on SIMD registers rather than
    # through a @vectorize wrapper.
    shifted = sint(size=value.size)
    shrsi2(shifted, value << (RING_BITS - split_k), RING_BITS - split_k + m)
    result = shifted + sint.conv(low) - (high << (split_k - m))
    if signed:
        result = result - (1 << (k - m - 1))
    if return_sign:
        sign_index = k - 1
        carry_into_sign = comparison.CarryOutRawLE(
            x[1][:sign_index], x[0][:sign_index])
        encoded_sign = (carry_into_sign ^ x[0][sign_index]
                        ^ x[1][sign_index])
        return result, 1 - encoded_sign if signed else 0
    return result

def trunc_floor_bounded(value, k, m, signed=True):
    result = sint(size=value.size)
    _trunc_floor_bounded2_cisc(result, value, k, m, signed)
    return result

@instructions_base.cisc
def _trunc_floor_bounded2_cisc(result, value, k, m, signed):
    movs(result, _trunc_floor_split2(value, k, m, k, signed=signed))

def trunc_round_nearest_with_sign(value, k, m, bounded=False):
    if m == 0:
        sign = value.less_than(0, k, maybe_mixed=True)
        return value, sign
    return _trunc_floor_split2(
        value + (1 << (m - 1)), k + 1, m, k + 1 if bounded else RING_BITS,
        signed=True, return_sign=True)

def truncate_generic(value, k, m):
    """Route the generic frontier through the two-summand kernel as well.

    The three-summand bounded split gains nothing once the declaration fills
    the ring -- it splits the whole ring either way -- which is why
    ``_bounded_split`` sends those sites to MP-SPDZ's ``TruncRing``.  The
    two-summand kernel does not converge with it: at ring32 a declaration of 31
    costs 65.4 B against 92.6 B.  The identity is unchanged and was checked
    bit-exact against ``TruncRing`` at the ring-filling width, so the site is
    taken here whenever the split still fits.
    """
    if m == 0:
        return value
    if not sfix.round_nearest or k + 1 > RING_BITS:
        return _generic_truncation(value, k, m)
    return trunc_floor_bounded(value + (1 << (m - 1)), k + 1, m, signed=True)
'''

TWO_SUMMAND_SIGN_HELPER = '''
def is_negative(value, k):
    """Sign over the two-summand regrouping instead of MP-SPDZ's comparison.

    ``less_than`` reads ``program.use_split()`` and therefore compresses three
    summands before its carry chain runs.  The sign is the top bit of the sum of
    the split columns, so over two summands it is the same chain without the
    Wallace level, at the price of the ``split(2)`` input.  Measured at ring32:
    ``8.84 + 1.228 k`` bytes per element against ``9.21 + 1.478 k``, and one
    extra round per site (PLAN 9 section 4.9).  Verified bit-identical to
    ``less_than(0, k)`` on live sharings, including values re-shared by a
    multiplication.
    """
    columns = value.split_to_n_summands(k, 2)
    x = [[column[0] for column in columns], [column[1] for column in columns]]
    top = k - 1
    carry = comparison.CarryOutRawLE(x[1][:top], x[0][:top])
    return sint.conv(carry ^ x[0][top] ^ x[1][top])
'''

