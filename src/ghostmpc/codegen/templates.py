SCORE_BLOCK = '''score_probe = {embedding}.get_vector().v
score_row = {row} * EMBEDDING_SIZE
score_output[0] = sint.dot_product(
    score_probe, gallery.get_vector(score_row, EMBEDDING_SIZE))
score_output[1] = sint.dot_product(score_probe, score_probe)
'''

# A probe that declares no identity is ranked against every enrolled
# row, so the answer is an index rather than a similarity: ``identify_output``
# holds the rank-1 row and the accumulator that won it, and the servers hand
# back share components of both without opening either.
IDENTIFY_SETUP = '''CANDIDATES = {candidates}
identify_output = sint.Array(2)

'''

# The ``N`` similarities.  ``||g_i|| = 1`` and ``||e||`` does not depend on
# ``i``, so ranking the cosines is ranking these accumulators: no norm, no
# division, no square root -- and, because nothing is squared, no truncation
# either.  The row address is a compile-time constant, so the whole gather is
# local and the only interaction is the re-sharing of one ring element per row.
IDENTIFY_SIMILARITIES = '''identify_probe = {embedding}.get_vector().v
identify_level0 = sint.Array(CANDIDATES)
for _row in range(CANDIDATES):
    identify_level0[_row] = sint.dot_product(
        identify_probe, gallery.get_vector(_row * EMBEDDING_SIZE, EMBEDDING_SIZE))
'''

# One level of the tournament, vectorized: the vector is folded in half, so
# element ``i`` meets element ``i + W`` and **both operands are contiguous
# slices**.  Pairing adjacent elements instead would need a strided gather
# through raw address vectors, and a raw ``load_mem`` is not tracked as a use of
# the array it reads: under ``unlimited_compilation`` with memory reuse the
# allocator recycles the array first and the level reads zeros.  That was
# measured, not feared -- the strided form returned the wrong rank-1 row on a
# live run -- so the fold is the realization and the oracle mirrors it.
IDENTIFY_LEVEL = '''identify_left = {values}.get_vector(0, {width})
identify_right = {values}.get_vector({width}, {width})
identify_bit = is_negative(identify_left - identify_right, {difference_bits})
{next_values} = sint.Array({next_length})
{next_values}.assign_vector(
    identify_left + identify_bit * (identify_right - identify_left))
'''

# At the first level the two candidate indices are *public* -- ``i`` and
# ``i + W`` -- so the winner is ``i + bW``: a secret bit times a public constant
# added to a public vector, which communicates nothing.  Only from the second
# level on does the index become secret and its selection cost a product.
IDENTIFY_INDEX_FIRST = '''{next_index} = sint.Array({next_length})
{next_index}.assign_vector(identify_bit * {width} + regint.inc({width}, 0, 1))
'''

IDENTIFY_INDEX = '''identify_index_left = {index}.get_vector(0, {width})
identify_index_right = {index}.get_vector({width}, {width})
{next_index} = sint.Array({next_length})
{next_index}.assign_vector(
    identify_index_left
    + identify_bit * (identify_index_right - identify_index_left))
'''

# An odd level has nobody to fold its last element onto, so it carries forward
# untouched.  Padding the database instead would need a sentinel similarity no
# real row can reach, which is a bound that would then have to be certified.
IDENTIFY_CARRY = '''{next_values}[{last}] = {values}[{last_source}]
{next_index}[{last}] = {index}[{last_source}]
'''

IDENTIFY_CARRY_FIRST = '''{next_values}[{last}] = {values}[{last_source}]
{next_index}[{last}] = sint({last_source})
'''

IDENTIFY_OUTPUT = '''identify_output[0] = {index}[0]
identify_output[1] = {values}[0]
'''
