from __future__ import annotations

"""The naive MP-SPDZ baseline: a straightforward scalar emitter.

This is the emitter as it stood before any of the optimizations of the paper:
scalar kernels, one truncation per linear output, no fusion and no graph
rewriting, on a 64-bit ring at f = 20.  Model parameters are public ``cint``
values, so linear layers perform local secret-by-public arithmetic.  The only
additions to that historical emitter are the warm-up requests, the measurement
timers and the naive ``sfix`` verification score, so that its program is read
by the same harness as every other row.
"""

from dataclasses import dataclass
from pathlib import Path
import math
import re
from typing import Any

from .model import Manifest, Op


HEADER = '''# Generated by ghostmpc. Do not edit.
from Compiler.types import sfix, sint, cint, MemValue
from Compiler.library import for_range, for_range_multithread, print_ln, public_input, start_timer, stop_timer, if_

program.options_from_args()
# Both supported protocols implement direct arithmetic/binary conversion.
# One summand per party avoids the much more expensive generic edaBit path.
program.use_split({parties})
sfix.set_precision({fractional_bits}, {total_bits})
sfix.round_nearest = {round_nearest}
INPUT_SIZE = {input_size}
PARTIES = {parties}
THREADS = {threads}
REQUESTS = {requests}
WARMUPS = {warmups}
PUBLIC_WEIGHT_COUNT = {weight_count}
BINARY_INPUT = True
# The timer identifiers of the current harness, so that a program emitted from
# this historical revision is read by the same parser as every other row it is
# compared against.  They are the only thing this revision borrows from the
# present: the arithmetic below is untouched.
MEASURED_TIMER_ID = 20000
WEIGHT_LOAD_TIMER_ID = 20001
INPUT_SHARE_TIMER_ID = 20002
EMBEDDING_TIMER_ID = 20003
SCORE_TIMER_ID = 20004
GALLERY_LOAD_TIMER_ID = 20005
MATCH_TIMER_ID = 20006

{weight_load_open}public_weights = cint.Array(PUBLIC_WEIGHT_COUNT)
@for_range(PUBLIC_WEIGHT_COUNT)
def _(i):
    public_weights[i] = public_input()
{weight_load_close}
def secret_input(n=INPUT_SIZE):
    # Every server receives one additive raw-ring component. MP-SPDZ turns
    # each component into a protocol-native sharing before they are summed.
    components = []
    for party in range(PARTIES):
        component = sint.Array(n)
        component.input_from(party, binary=BINARY_INPUT)
        components.append(component.get_vector())
    raw = components[0]
    for component in components[1:]:
        raw = raw + component
    result = sfix.Array(n)
    result.assign(sfix._new(raw))
    return result

{score_setup}def marker(phase, name):
    print_ln('GHOSTMPC_MARKER %s %s', phase, name)

'''


# The naive score: an ``sfix`` elementwise product of probe and row, so 512
# secret multiplications and a 512-wide truncation per inner product, then a
# local sum.  This is what a straightforward implementation of the score looks
# like, which is the entire point of measuring it here.
SCORE_SETUP = '''GALLERY_ROWS = {gallery_rows}
EMBEDDING_SIZE = {embedding_size}
GALLERY_SIZE = GALLERY_ROWS * EMBEDDING_SIZE

def gallery_input(n):
    # Raw ring integers on the gallery grid 2^{gallery_fractional_bits}.  The
    # dealer distributed one additive component per server, exactly as the
    # client does for the image.
    components = []
    for party in range(PARTIES):
        component = sint.Array(n)
        component.input_from(party, binary=BINARY_INPUT)
        components.append(component.get_vector())
    raw = components[0]
    for component in components[1:]:
        raw = raw + component
    return raw

{gallery_load_open}gallery = sint.Array(GALLERY_SIZE)
gallery.assign(gallery_input(GALLERY_SIZE))
{gallery_load_close}score_output = sint.Array(2)
{match_setup}
'''

SCORE_BLOCK = '''score_probe = {embedding}.get_vector().v
score_row = (request_id % GALLERY_ROWS) * EMBEDDING_SIZE
score_products = sfix.Array(EMBEDDING_SIZE)
score_products.assign(
    sfix._new(score_probe)
    * sfix._new(gallery.get_vector(score_row, EMBEDDING_SIZE)))
score_squares = sfix.Array(EMBEDDING_SIZE)
score_squares.assign(sfix._new(score_probe) * sfix._new(score_probe))
score_output[0] = sum(score_products[j] for j in range(EMBEDDING_SIZE)).v
score_output[1] = sum(score_squares[j] for j in range(EMBEDDING_SIZE)).v
'''

def _gated(statement: str) -> str:
    return f"@if_(request_id >= WARMUPS)\ndef _():\n    {statement}\n"


@dataclass(frozen=True)
class WeightPlan:
    values: Any
    offsets: dict[str, int]
    lengths: dict[str, int]


def _size(shape: list[int]) -> int:
    return math.prod(shape)


def _ident(name: str) -> str:
    return "v_" + re.sub(r"[^A-Za-z0-9_]", "_", name)


def _offset(offsets: dict[str, int], name: str) -> int:
    if name not in offsets:
        raise ValueError(f"public tensor {name!r} is missing from the weight plan")
    return offsets[name]


def _copy(target: str, source: str, size: int) -> str:
    return f"{target} = sfix.Array({size})\n{target}.assign({source}.get_vector())\n"


def _public_scaled_vector(name: str, size: int, tensor_offset: int, channels: int) -> str:
    return f'''{name} = cint.Array({size})
@for_range({size})
def _(i):
    {name}[i] = public_weights[{tensor_offset} + i % {channels}]
'''


def _truncate(raw: str, target: str, size: int, bias_offset: int | None = None,
              channels: int | None = None) -> str:
    lines = [f"{target} = sfix.Array({size})\n"]
    expression = f"{raw}.get_vector().round(sfix.k + sfix.f, sfix.f, nearest=sfix.round_nearest)"
    if bias_offset is not None:
        bias = f"{target}_bias"
        lines.append(_public_scaled_vector(bias, size, bias_offset, channels or size))
        expression += f" + {bias}.get_vector()"
    lines.append(f"{target}.assign(sfix._new({expression}))\n")
    return "".join(lines)


def _conv2d(op: Op, target: str, source: str, input_shape: list[int],
            offsets: dict[str, int]) -> str:
    input_h, input_w, input_c = input_shape
    output_h, output_w, output_c = op.output_shape
    kernel_h, kernel_w = op.params["kernel_size"]
    stride_h, stride_w = op.params["strides"]
    if op.params["padding"] == "SAME":
        total_pad_h = max((output_h - 1) * stride_h + kernel_h - input_h, 0)
        total_pad_w = max((output_w - 1) * stride_w + kernel_w - input_w, 0)
        pad_h, pad_w = total_pad_h // 2, total_pad_w // 2
    else:
        total_pad_h = total_pad_w = pad_h = pad_w = 0
    kernel_offset = _offset(offsets, op.tensors[0])
    bias_offset = _offset(offsets, op.tensors[1]) if len(op.tensors) > 1 else None
    output_size = _size(op.output_shape)
    raw = f"{target}_raw"
    padded = source
    if total_pad_h or total_pad_w:
        padded = f"{target}_padded"
        padded_h, padded_w = input_h + total_pad_h, input_w + total_pad_w
        prefix = f'''{padded} = sfix.Array({padded_h * padded_w * input_c})
{padded}.assign_all(0)
@for_range({input_h * input_w * input_c})
def _(i):
    channel = i % {input_c}
    in_x = (i // {input_c}) % {input_w}
    in_y = i // {input_c * input_w}
    {padded}[((in_y + {pad_h}) * {padded_w} + in_x + {pad_w}) * {input_c} + channel] = {source}[i]
'''
    else:
        padded_h, padded_w = input_h, input_w
        prefix = ""
    lines = [prefix, f'''{raw} = sint.Array({output_size})
@for_range_multithread(THREADS, 1, {output_size})
def _(i):
    out_c = i % {output_c}
    out_x = (i // {output_c}) % {output_w}
    out_y = i // {output_c * output_w}
    acc = MemValue(sint(0))
''']
    for ky in range(kernel_h):
        for kx in range(kernel_w):
            lines.append(f"    in_y = out_y * {stride_h} + {ky}\n    in_x = out_x * {stride_w} + {kx}\n")
            for in_c in range(input_c):
                weight_base = kernel_offset + ((ky * kernel_w + kx) * input_c + in_c) * output_c
                lines.append(
                    f"    acc.iadd({padded}[(in_y * {padded_w} + in_x) * {input_c} + {in_c}].v "
                    f"* public_weights[{weight_base} + out_c])\n"
                )
    lines.append(f"    {raw}[i] = acc.read()\n")
    lines.append(_truncate(raw, target, output_size, bias_offset, output_c))
    return "".join(lines)


def _depthwise_conv2d(op: Op, target: str, source: str, input_shape: list[int],
                      offsets: dict[str, int]) -> str:
    input_h, input_w, input_c = input_shape
    output_h, output_w, output_c = op.output_shape
    kernel_h, kernel_w = op.params["kernel_size"]
    stride_h, stride_w = op.params["strides"]
    multiplier = int(op.params.get("depth_multiplier", 1))
    if output_c != input_c * multiplier:
        raise ValueError(f"invalid depthwise shape in {op.name}")
    if op.params["padding"] == "SAME":
        total_pad_h = max((output_h - 1) * stride_h + kernel_h - input_h, 0)
        total_pad_w = max((output_w - 1) * stride_w + kernel_w - input_w, 0)
        pad_h, pad_w = total_pad_h // 2, total_pad_w // 2
    else:
        total_pad_h = total_pad_w = pad_h = pad_w = 0
    kernel_offset = _offset(offsets, op.tensors[0])
    bias_offset = _offset(offsets, op.tensors[1]) if len(op.tensors) > 1 else None
    output_size = _size(op.output_shape)
    raw = f"{target}_raw"
    padded = source
    if total_pad_h or total_pad_w:
        padded = f"{target}_padded"
        padded_h, padded_w = input_h + total_pad_h, input_w + total_pad_w
        prefix = f'''{padded} = sfix.Array({padded_h * padded_w * input_c})
{padded}.assign_all(0)
@for_range({input_h * input_w * input_c})
def _(i):
    channel = i % {input_c}
    in_x = (i // {input_c}) % {input_w}
    in_y = i // {input_c * input_w}
    {padded}[((in_y + {pad_h}) * {padded_w} + in_x + {pad_w}) * {input_c} + channel] = {source}[i]
'''
    else:
        padded_h, padded_w = input_h, input_w
        prefix = ""
    lines = [prefix, f'''{raw} = sint.Array({output_size})
@for_range_multithread(THREADS, 1, {output_size})
def _(i):
    out_c = i % {output_c}
    in_c = out_c // {multiplier}
    depth_index = out_c % {multiplier}
    out_x = (i // {output_c}) % {output_w}
    out_y = i // {output_c * output_w}
    acc = MemValue(sint(0))
''']
    for ky in range(kernel_h):
        for kx in range(kernel_w):
            weight_base = kernel_offset + (ky * kernel_w + kx) * input_c * multiplier
            lines.append(
                f"    in_y = out_y * {stride_h} + {ky}\n"
                f"    in_x = out_x * {stride_w} + {kx}\n"
                f"    acc.iadd({padded}[(in_y * {padded_w} + in_x) * {input_c} + in_c].v "
                f"* public_weights[{weight_base} + in_c * {multiplier} + depth_index])\n"
            )
    lines.append(f"    {raw}[i] = acc.read()\n")
    lines.append(_truncate(raw, target, output_size, bias_offset, output_c))
    return "".join(lines)


def _quadratic(target: str, source: str, size: int, coefficients: list[float]) -> str:
    if len(coefficients) != 3:
        raise ValueError("quadratic activation requires [a, b, c]")
    a, b, c = (float(x) for x in coefficients)
    return f'''{target} = sfix.Array({size})
{target}_values = {source}.get_vector()
{target}_square = {target}_values * {target}_values
{target}.assign({a!r} * {target}_square + {b!r} * {target}_values + {c!r})
'''


def _prelu(op: Op, target: str, source: str, size: int,
           offsets: dict[str, int]) -> str:
    if op.params.get("approximation") == "quadratic":
        return _quadratic(target, source, size, op.params["coefficients"])
    alpha_offset = _offset(offsets, op.tensors[0])
    channels = op.output_shape[-1]
    alpha = f"{target}_alpha"
    return (
        _public_scaled_vector(alpha, size, alpha_offset, channels)
        + f'''{target} = sfix.Array({size})
{target}_negative_raw = {source}.get_vector().v * {alpha}.get_vector()
{target}_negative = sfix._new({target}_negative_raw.round(sfix.k + sfix.f, sfix.f, nearest=sfix.round_nearest))
{target}_values = {source}.get_vector()
{target}.assign(({target}_values >= 0).if_else({target}_values, {target}_negative))
'''
    )


def _batchnorm(op: Op, target: str, source: str, size: int,
               offsets: dict[str, int]) -> str:
    channels = op.output_shape[-1]
    scale_offset = _offset(offsets, f"{op.name}:affine_scale")
    bias_offset = _offset(offsets, f"{op.name}:affine_bias")
    scale = f"{target}_scale"
    bias = f"{target}_affine_bias"
    return (
        _public_scaled_vector(scale, size, scale_offset, channels)
        + _public_scaled_vector(bias, size, bias_offset, channels)
        + f'''{target} = sfix.Array({size})
{target}_raw = {source}.get_vector().v * {scale}.get_vector()
{target}_scaled = {target}_raw.round(sfix.k + sfix.f, sfix.f, nearest=sfix.round_nearest)
{target}.assign(sfix._new({target}_scaled + {bias}.get_vector()))
'''
    )


def _concat(op: Op, target: str, sources: list[str], shapes: list[list[int]]) -> str:
    axis = int(op.params.get("axis", -1))
    rank = len(op.output_shape)
    if axis < 0:
        axis += rank
    if axis != rank - 1:
        raise ValueError(f"{op.name}: only channel-last concatenation is supported")
    output_size = _size(op.output_shape)
    output_channels = op.output_shape[-1]
    outer = output_size // output_channels
    lines = [f"{target} = sfix.Array({output_size})\n", "channel_offset = 0\n"]
    for source, shape in zip(sources, shapes):
        channels = shape[-1]
        lines.append(
            f"@for_range({outer})\n"
            "def _(position):\n"
            f"    @for_range({channels})\n"
            "    def _(channel):\n"
            f"        {target}[position * {output_channels} + channel_offset + channel] = "
            f"{source}[position * {channels} + channel]\n"
        )
        lines.append(f"channel_offset += {channels}\n")
    return "".join(lines)


def _add(target: str, sources: list[str], size: int) -> str:
    expression = " + ".join(f"{source}.get_vector()" for source in sources)
    return f"{target} = sfix.Array({size})\n{target}.assign({expression})\n"


def _multiply(target: str, sources: list[str], sizes: list[int], size: int) -> str:
    lines = [f"{target} = sfix.Array({size})\n"]
    vectors: list[str] = []
    for index, (source, source_size) in enumerate(zip(sources, sizes)):
        if source_size == size:
            vectors.append(f"{source}.get_vector()")
        else:
            expanded = f"{target}_broadcast_{index}"
            lines.append(f"{expanded} = sfix.Array({size})\n@for_range({size})\ndef _(i):\n    {expanded}[i] = {source}[i % {source_size}]\n")
            vectors.append(f"{expanded}.get_vector()")
    lines.append(f"{target}.assign({' * '.join(vectors)})\n")
    return "".join(lines)


def _global_average_pool(target: str, source: str, input_shape: list[int]) -> str:
    height, width, channels = input_shape
    spatial = height * width
    return f'''{target} = sfix.Array({channels})
@for_range_multithread(THREADS, 1, {channels})
def _(channel):
    acc = MemValue(sint(0))
    @for_range({spatial})
    def _(position):
        acc.iadd({source}[position * {channels} + channel].v)
    {target}[channel] = sfix._new(acc.read()) * {1 / spatial!r}
'''


def _activation(op: Op, target: str, source: str, size: int, activation: str) -> str:
    if op.params.get("approximation") == "quadratic":
        return _quadratic(target, source, size, op.params["coefficients"])
    if activation == "linear":
        return _copy(target, source, size)
    if activation in {"sigmoid", "hard_sigmoid"}:
        return f'''{target} = sfix.Array({size})
{target}_raw = 0.2 * {source}.get_vector() + 0.5
{target}.assign(({target}_raw < 0).if_else(0, ({target}_raw > 1).if_else(1, {target}_raw)))
'''
    raise ValueError(f"unsupported activation in generator: {activation}")


def _layer_code(op: Op, target: str, sources: list[str], input_shapes: list[list[int]],
                offsets: dict[str, int]) -> str:
    output_size = _size(op.output_shape)
    input_sizes = [_size(shape) for shape in input_shapes]
    if op.kind == "Conv2D":
        return _conv2d(op, target, sources[0], input_shapes[0], offsets)
    if op.kind == "DepthwiseConv2D":
        return _depthwise_conv2d(op, target, sources[0], input_shapes[0], offsets)
    if op.kind == "BatchNormalization":
        return _batchnorm(op, target, sources[0], output_size, offsets)
    if op.kind == "PReLU":
        return _prelu(op, target, sources[0], output_size, offsets)
    if op.kind == "Concatenate":
        return _concat(op, target, sources, input_shapes)
    if op.kind == "Add":
        return _add(target, sources, output_size)
    if op.kind == "Multiply":
        return _multiply(target, sources, input_sizes, output_size)
    if op.kind == "GlobalAveragePooling2D":
        return _global_average_pool(target, sources[0], input_shapes[0])
    if op.kind == "Activation":
        return _activation(op, target, sources[0], output_size, op.params["activation"])
    if op.kind in {"Reshape", "Flatten"}:
        return ""
    raise ValueError(f"unsupported op in generator: {op.kind}")


def _default_offsets(manifest: Manifest) -> tuple[dict[str, int], dict[str, int]]:
    offsets = {tensor.name: tensor.offset for tensor in manifest.tensors}
    lengths = {tensor.name: tensor.length for tensor in manifest.tensors}
    return offsets, lengths


def render(manifest: Manifest, fractional_bits: int = 20, only_layer: str | None = None,
           *, parties: int = 2, threads: int = 1, requests: int = 1,
           ring_bits: int = 64, weight_offsets: dict[str, int] | None = None,
           weight_count: int | None = None, round_nearest: bool = True,
           test_reveal: bool = False, warmups: int = 0,
           measured_timer: bool = False,
           score: dict[str, int] | None = None) -> str:
    if parties not in (2, 3):
        raise ValueError("only two-party Semi2k and three-party Rep3 are supported")
    if ring_bits not in (32, 64):
        raise ValueError("ring bits must be 32 or 64")
    total_bits = 31 if ring_bits == 64 else 15
    if fractional_bits >= total_bits:
        raise ValueError("fractional precision must be smaller than total fixed-point bits")
    default_offsets, _ = _default_offsets(manifest)
    offsets = weight_offsets or default_offsets
    if weight_count is None:
        weight_count = max((tensor.offset + tensor.length for tensor in manifest.tensors), default=0)
    score_setup = ""
    if score is not None:
        score_setup = SCORE_SETUP.format(
            gallery_rows=int(score["gallery_rows"]),
            embedding_size=int(score["embedding_size"]),
            gallery_fractional_bits=int(score["gallery_fractional_bits"]),
            gallery_load_open=(f"start_timer(GALLERY_LOAD_TIMER_ID)\n"
                               if measured_timer else ""),
            gallery_load_close=(f"stop_timer(GALLERY_LOAD_TIMER_ID)\n"
                                if measured_timer else ""),
            match_setup="",
        )
    lines = [HEADER.format(
        fractional_bits=fractional_bits, total_bits=total_bits,
        round_nearest=str(bool(round_nearest)), input_size=_size(manifest.input_shape),
        parties=parties, threads=max(1, threads), requests=max(1, requests),
        warmups=max(0, warmups), weight_count=weight_count,
        weight_load_open=("start_timer(WEIGHT_LOAD_TIMER_ID)\n"
                          if measured_timer else ""),
        weight_load_close=("stop_timer(WEIGHT_LOAD_TIMER_ID)\n"
                           if measured_timer else ""),
        score_setup=score_setup,
    )]
    producer_shapes = {op.name: op.output_shape for op in manifest.ops}
    selected = [op for op in manifest.ops if only_layer is None or op.name == only_layer]
    if only_layer and not selected:
        raise KeyError(f"unknown layer {only_layer}")
    first_inputs = manifest.ops[0].inputs if manifest.ops else []
    input_size = _size(manifest.input_shape)
    if only_layer:
        first_shape = producer_shapes.get(selected[0].inputs[0], manifest.input_shape)
        input_size = _size(first_shape)
    lines.append("@for_range(REQUESTS)\ndef _(request_id):\n")
    body: list[str] = []
    if measured_timer:
        # The measured timer brackets only the post-warm-up requests; MP-SPDZ
        # timers accumulate, so starting and stopping inside the loop under the
        # same predicate discards the cold ones rather than averaging them in.
        body.append(_gated("start_timer(MEASURED_TIMER_ID)"))
        body.append(_gated("start_timer(INPUT_SHARE_TIMER_ID)"))
    body.append(f"input_value = secret_input({input_size})\n")
    if measured_timer:
        body.append(_gated("stop_timer(INPUT_SHARE_TIMER_ID)"))
    split_timers = measured_timer and score is not None
    if split_timers:
        body.append(_gated("start_timer(EMBEDDING_TIMER_ID)"))
    values: dict[str, str] = {"input": "input_value"}
    shapes: dict[str, list[int]] = {"input": manifest.input_shape}
    for name in first_inputs:
        values[name] = "input_value"
        shapes[name] = manifest.input_shape
    if only_layer:
        first_shape = producer_shapes.get(selected[0].inputs[0], manifest.input_shape)
        for name in selected[0].inputs:
            values[name], shapes[name] = "input_value", producer_shapes.get(name, first_shape)
    for op in selected:
        sources = [values.get(name, "input_value") for name in op.inputs]
        input_shapes = [shapes.get(name, producer_shapes.get(name, manifest.input_shape)) for name in op.inputs]
        target = _ident(op.name)
        body.append(f"marker('start', '{op.name}')\nstart_timer(1)\n")
        code = _layer_code(op, target, sources, input_shapes, offsets)
        body.append(code)
        body.append(f"stop_timer(1)\nmarker('stop', '{op.name}')\n")
        if op.kind in {"Reshape", "Flatten"}:
            values[op.name] = sources[0]
        else:
            values[op.name] = target
        shapes[op.name] = op.output_shape
    if split_timers:
        body.append(_gated("stop_timer(EMBEDDING_TIMER_ID)"))
    if test_reveal and selected:
        # With a score compiled in the equivalence gate recomputes the score
        # from this vector, so it needs the raw ring integers: printing the
        # sfix would hand it rounded decimals and make the comparison a
        # tolerance instead of an equality.
        opened = (f"{values[selected[-1].name]}.get_vector()"
                  + (".v" if score is not None else ""))
        body.append(f"print_ln('GHOSTMPC_TEST_OUTPUT %s', {opened}.reveal())\n")
    else:
        body.append("# The embedding remains secret-shared; no server reveals it.\n")
    if score is not None and selected:
        # The servers open nothing: ``score_output`` holds two secret-shared
        # ring elements whose components each server returns to the client.
        body.append("marker('start', 'score')\n")
        if measured_timer:
            body.append(_gated("start_timer(SCORE_TIMER_ID)"))
        body.append(SCORE_BLOCK.format(embedding=values[selected[-1].name]))
        if measured_timer:
            body.append(_gated("stop_timer(SCORE_TIMER_ID)"))
        body.append("marker('stop', 'score')\n")
        if test_reveal:
            body.append(
                "print_ln('GHOSTMPC_TEST_SCORE %s %s', "
                "score_output[0].reveal(), score_output[1].reveal())\n")
    if measured_timer:
        body.append(_gated("stop_timer(MEASURED_TIMER_ID)"))
    lines.extend("    " + line if line.strip() else line for chunk in body for line in chunk.splitlines(keepends=True))
    return "".join(lines)


def _prepare_weights(manifest: Manifest, weights: Any, selected: set[str] | None = None) -> WeightPlan:
    import numpy as np

    refs = {tensor.name: tensor for tensor in manifest.tensors}
    chunks: list[Any] = []
    offsets: dict[str, int] = {}
    lengths: dict[str, int] = {}
    cursor = 0

    def append(name: str, values: Any) -> None:
        nonlocal cursor
        flat = np.asarray(values, dtype=np.float64).reshape(-1)
        offsets[name], lengths[name] = cursor, int(flat.size)
        chunks.append(flat)
        cursor += int(flat.size)

    for op in manifest.ops:
        if selected is not None and op.name not in selected:
            continue
        if op.kind == "BatchNormalization" and len(op.tensors) == 4:
            arrays = [weights[refs[name].offset:refs[name].offset + refs[name].length] for name in op.tensors]
            gamma, beta, mean, variance = arrays
            if not op.params.get("scale", True):
                gamma = np.ones_like(mean)
            if not op.params.get("center", True):
                beta = np.zeros_like(mean)
            scale = gamma / np.sqrt(variance + float(op.params["epsilon"]))
            append(f"{op.name}:affine_scale", scale)
            append(f"{op.name}:affine_bias", beta - mean * scale)
            continue
        for name in op.tensors:
            ref = refs[name]
            append(name, weights[ref.offset:ref.offset + ref.length])
    values = np.concatenate(chunks) if chunks else np.empty(0, dtype=np.float64)
    return WeightPlan(values, offsets, lengths)


def _public_input_path(output: Path) -> Path:
    if output.parent.name == "Source":
        return output.parent.parent / "Public-Input" / output.stem
    return output.with_suffix(".public-input")


def _write_public_weights(path: Path, values: Any, fractional_bits: int,
                          ring_bits: int) -> None:
    import numpy as np

    scaled = np.rint(values * (1 << fractional_bits))
    limit = 1 << (ring_bits - 1)
    if np.any(scaled < -limit) or np.any(scaled >= limit):
        raise OverflowError("a public model parameter is outside the selected ring")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as handle:
        for start in range(0, len(scaled), 65536):
            np.savetxt(handle, scaled[start:start + 65536].astype(np.int64), fmt="%d")


def generate(manifest_path: Path, output: Path, fractional_bits: int | None = None,
             only_layer: str | None = None, *, parties: int = 2, threads: int = 1,
             requests: int = 1, ring_bits: int | None = None,
             round_nearest: bool = True, test_reveal: bool = False,
             warmups: int = 0, measured_timer: bool = False,
             score: dict[str, int] | None = None) -> Path:
    import numpy as np

    manifest = Manifest.load(manifest_path)
    fractional_bits = fractional_bits if fractional_bits is not None else manifest.quantization.fractional_bits
    ring_bits = ring_bits if ring_bits is not None else manifest.quantization.ring_bits
    weights_path = manifest_path.parent / manifest.weights_file
    if not weights_path.is_file():
        if manifest.tensors:
            raise FileNotFoundError(weights_path)
        weights = np.empty(0, dtype=np.float64)
    else:
        weights = np.load(weights_path, mmap_mode="r")
    selected = {only_layer} if only_layer else None
    plan = _prepare_weights(manifest, weights, selected)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(
        manifest, fractional_bits, only_layer, parties=parties, threads=threads,
        requests=requests, ring_bits=ring_bits, weight_offsets=plan.offsets,
        weight_count=len(plan.values), round_nearest=round_nearest,
        test_reveal=test_reveal, warmups=warmups,
        measured_timer=measured_timer, score=score,
    ))
    public_input_path = _public_input_path(output)
    _write_public_weights(public_input_path, plan.values, fractional_bits, ring_bits)
    return public_input_path
